"""The statistical analysis of the production-test week. Writes results/report.md,
results/summary.json and the figures in docs/img/.

    python analyse.py

Each section answers one question a quality engineer would ask, with the method from the
Probability Theory and Mathematical Statistics course that fits it. The data: data/measurements.csv and data/runs.csv
(tools/export_data.py, from the production-test-db project).
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy import stats as sd  # noqa: E402

from spc import capability as cap  # noqa: E402
from spc import charts  # noqa: E402
from spc import stats as st  # noqa: E402

ROOT = Path(__file__).resolve().parent
DAYS = ["Mon", "Tue", "Wed", "Thu", "Fri"]
PHASE1 = ["Mon", "Tue"]                 # the period used to set limits: before any known problem
ALPHA = 0.05
BLUE, RED, GREEN, GREY, ORANGE = "#1f5fa8", "#c23b3b", "#2a9d4b", "#888888", "#d9822b"


def load():
    m = pd.read_csv(ROOT / "data/measurements.csv", parse_dates=["started_at"])
    r = pd.read_csv(ROOT / "data/runs.csv", parse_dates=["started_at"])
    for df in (m, r):
        df["day"] = pd.Categorical(df["day"], DAYS, ordered=True)
        # production time in days: Monday 06:00 = 0, each shift day 06:00-21:00 maps to one unit
        hours = df["started_at"].dt.hour + df["started_at"].dt.minute / 60
        df["t_day"] = df["day"].cat.codes + (hours - 6) / 15
    return m.sort_values(["started_at", "run_id"]), r.sort_values(["started_at", "run_id"])


def fmt_p(p):
    return "< 0.0001" if p < 1e-4 else f"{p:.4f}"


def P(p):
    return "p < 0.0001" if p < 1e-4 else f"p = {p:.4f}"


def fmt_ci(ci, nd=3):
    return f"[{ci[0]:.{nd}f}, {ci[1]:.{nd}f}]"


def main():
    m, runs = load()
    first = m[m.attempt == 1]
    out = {}
    md = ["# Results", "", "Generated by `python analyse.py` from `data/measurements.csv` (1,380 measurements) and "
          "`data/runs.csv` (1,080 test runs). Significance level 0.05 throughout.", ""]

    # ================================================================ 1. describe + normality
    md += ["## 1. What does a normal week look like? (description, normality)", "",
           "First-attempt measurements on Monday and Tuesday, the phase-I period before any known problem.", "",
           "| Product | Quantity | Station | n | Mean | SD | Median | Skew | Shapiro-Wilk p | 95 % CI of the mean | 95 % CI of the SD |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    out["describe"] = {}
    rejected = []
    for _, g in first[first.day.isin(PHASE1)].groupby("spec_id"):
        q, station, prod = g.quantity.iloc[0], g.station.iloc[0], g["product"].iloc[0]
        d = st.describe(g.value)
        sw = st.shapiro(g.value)
        md.append(f"| {prod} | {q} | {station} | {d['n']} | {d['mean']:.3f} | {d['sd']:.3f} | {d['median']:.3f} | "
                  f"{d['skew']:+.2f} | {sw.p:.3f} | {fmt_ci(st.ci_mean(g.value))} | {fmt_ci(st.ci_sd(g.value))} |")
        out["describe"][f"{prod} {q}"] = {**{k: float(v) for k, v in d.items()}, "shapiro_p": sw.p}
        if sw.reject():
            v = g.value.to_numpy()
            far = int(np.argmax(np.abs(v - v.mean())))
            outside = not (g.lower_limit.iloc[0] <= v[far] <= g.upper_limit.iloc[0])
            rejected.append((f"{prod} {q}", sw.p, v[far], (v[far] - v.mean()) / v.std(ddof=1),
                             st.shapiro(np.delete(v, far)).p, g.unit.iloc[0], outside))
    md.append("")
    n_tests = len(out["describe"])
    for name, p_, val, zv, p_wo, unit, outside in rejected:
        note = ("that part failed its test" if outside else "the part is still inside its specification")
        if p_ > 0.05 / n_tests:
            note += "; at the Bonferroni level (below) this rejection would not count"
        md.append(f"- **{name}: normality rejected ({P(p_)})**, caused by a single value, {val:g} {unit}, "
                  f"{zv:+.1f} standard deviations from the mean ({note}). Without it, Shapiro-Wilk gives {P(p_wo)}. "
                  "One extreme reading is enough to reject normality: look at that part before giving up the normal model.")
    lk12 = first[(first.spec_id == 5) & first.day.isin(PHASE1)].value
    gof = st.chi2_gof_normal(lk12, bins=6)
    out["gof_leak"] = {"chi2": gof.statistic, "p": gof.p, "df": gof.df, "observed": gof.observed.tolist()}
    md += ["", f"Chi-square goodness of fit for the leak rate (the course's test for a distribution): 6 classes of equal "
           f"probability under the fitted normal, observed counts {gof.observed.tolist()} against {len(lk12) / 6:.1f} expected "
           f"each; chi2 = {gof.statistic:.2f}, df = {gof.df}, {P(gof.p)}. Normality is "
           f"{'rejected' if gof.reject() else 'not rejected'}, in agreement with Shapiro-Wilk."]
    md += ["", f"With {n_tests} tests at the 5 % level, about {0.05 * n_tests:.1f} false rejections are expected by chance "
           f"alone (Bonferroni would test each at {0.05 / n_tests:.4f}). Apart from the single outliers above, the "
           "data is consistent with normal distributions, so the t intervals, 3-sigma control limits and normal-based "
           "capability indices below are reasonable. Not rejecting is not proof of normality; the Q-Q plots in "
           "`docs/img/qq.png` show the same.", ""]

    # ================================================================ 2. capability
    md += ["## 2. Is each process capable? (Cp, Cpk with confidence intervals)", "",
           "Phase-I data, sigma within from the moving range. Cpk 1.33 is the usual automotive minimum.", "",
           "| Product | Quantity | Station | Spec | n | Cp [95 % CI] | Cpk [95 % CI] | Ppk | Expected out of spec |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    out["capability"] = {}
    below, total = [], 0
    for _, g in first[first.day.isin(PHASE1)].groupby("spec_id"):
        q, station, prod = g.quantity.iloc[0], g.station.iloc[0], g["product"].iloc[0]
        lo, hi = g.lower_limit.iloc[0], g.upper_limit.iloc[0]
        lsl = None if lo == 0 and q in ("noise", "run_out", "leak_rate") else lo   # 0 is a natural bound
        c = cap.capability(g.value.to_numpy(), lsl, hi)
        cp = f"{c['Cp']:.2f} {fmt_ci(c['Cp_ci'], 2)}" if "Cp" in c else "one-sided"
        spec = f"{lo:g} to {hi:g}" if lsl is not None else f"<= {hi:g}"
        md.append(f"| {prod} | {q} | {station} | {spec} {g.unit.iloc[0]} | {c['n']} | {cp} | {c['Cpk']:.2f} "
                  f"{fmt_ci(c['Cpk_ci'], 2)} | {c['Ppk']:.2f} | {c['ppm']:,.0f} ppm |")
        total += 1
        if c["Cpk"] < 1.33:
            below.append(f"{prod} {q}")
        out["capability"][f"{prod} {q}"] = {k: (list(v) if isinstance(v, tuple) else float(v)) for k, v in c.items()}
    n_needed = cap.n_for_cpk_precision(1.33, 0.10)
    md += ["", f"**{len(below)} of {total} characteristics are below 1.33** in the first two days"
           + (f"; only {', '.join(sorted(set(out['capability']) - set(below)))} reaches it" if len(below) < total else "")
           + ". The intervals are wide: with 30-60 parts, a Cpk of 1.0 could be anything from about 0.8 to 1.25. "
           f"To know a Cpk of 1.33 to +-0.10 takes {n_needed} parts. "
           "The generated data has deliberately wide spreads (as noted in production-test-db), so the point here is "
           "the method and the trend, not the absolute values.", ""]

    leak = first[first.spec_id == 5].copy()
    md += ["LEAK-1 leak rate (upper limit 2.0 sccm) day by day:", "",
           "| Day | n | Mean | Cpk [95 % CI] | Expected out of spec | Actual failures |", "| --- | --- | --- | --- | --- | --- |"]
    out["leak_cpk_by_day"] = {}
    for day, g in leak.groupby("day", observed=True):
        c = cap.capability(g.value.to_numpy(), None, 2.0)
        fails = int((g.value > 2.0).sum())
        md.append(f"| {day} | {c['n']} | {c['mean']:.3f} | {c['Cpk']:.2f} {fmt_ci(c['Cpk_ci'], 2)} | "
                  f"{c['ppm'] / 1e4:.1f} % | {fails} |")
        out["leak_cpk_by_day"][day] = c["Cpk"]
    md.append("")

    # ================================================================ 3. control chart LEAK-1
    x = leak.value.to_numpy()
    ph1 = leak.day.isin(PHASE1).to_numpy()
    chart = charts.imr_chart(x, ph1)
    lim = chart.limits
    sig_idx = charts.first_signal({r: [i for i in v if not ph1[i]] for r, v in chart.signals.items()})
    rule1 = [i for i in chart.signals[1] if not ph1[i]]
    z, ewl, ewu = charts.ewma_chart(x, lim.centre, lim.sigma)
    ew_idx = next((i for i in range(x.size) if not ph1[i] and (z[i] > ewu[i] or z[i] < ewl[i])), None)
    fail_idx = int(np.argmax(x > 2.0)) if (x > 2.0).any() else None
    when = leak.started_at.dt.strftime("%a %H:%M").to_numpy()
    out["control_chart"] = {"centre": lim.centre, "ucl": lim.ucl, "sigma_within": lim.sigma,
                            "first_signal": when[sig_idx], "first_rule1": when[rule1[0]] if rule1 else None,
                            "first_ewma": when[ew_idx] if ew_idx is not None else None,
                            "first_fail": when[fail_idx] if fail_idx is not None else None,
                            "signals": {str(k): len([i for i in v if not ph1[i]]) for k, v in chart.signals.items()}}
    first_rule = min((r for r, v in chart.signals.items() if sig_idx in v))
    md += ["## 3. When could the seal wear have been caught? (I-MR and EWMA control charts)", "",
           f"Individuals chart of the LEAK-1 leak rate in time order. Limits from Monday and Tuesday: centre "
           f"{lim.centre:.3f} sccm, UCL {lim.ucl:.3f} sccm (sigma within {lim.sigma:.3f} from the moving range). "
           "Then Wednesday to Friday are plotted against the fixed limits.", "",
           "| Event | When |", "| --- | --- |",
           f"| first Western Electric signal (rule {first_rule}) | **{when[sig_idx]}** |",
           f"| first point beyond 3 sigma (rule 1) | {when[rule1[0]] if rule1 else '-'} |",
           f"| first EWMA signal (lambda 0.2, L 3) | {when[ew_idx] if ew_idx is not None else '-'} |",
           f"| first leak test failure (> 2.0 sccm) | **{when[fail_idx]}** |", "",
           "Signals per rule in phase II: " + ", ".join(f"rule {k}: {v}" for k, v in out["control_chart"]["signals"].items()) + ".",
           "", "The run rules and the EWMA react to the small shift long before a part fails: the seal could have been "
           "changed during Wednesday instead of failing parts on Thursday and Friday. Rule 1 alone (the plain 3-sigma "
           "limit) is slower; that is why the run rules exist.", ""]

    # ================================================================ 4. did it really change? tests
    a = leak[leak.day.isin(PHASE1)].value
    b = leak[leak.day.isin(["Thu", "Fri"])].value
    tw, tp, fv, mw = st.welch_t(b, a), st.pooled_t(b, a), st.f_test(b, a), st.mann_whitney(b, a)
    groups = [g.value.to_numpy() for _, g in leak.groupby("day", observed=True)]
    an, lv, kw = st.anova_oneway(*groups), st.levene(*groups), st.kruskal_wallis(*groups)
    tukey = sd.tukey_hsd(*groups)
    md += ["## 4. Is the rise real or chance? (two-sample tests, ANOVA)", "",
           "H0: the mean leak rate on Thursday-Friday equals Monday-Tuesday. H1: it differs.", "",
           "| Test | Statistic | p | Effect [95 % CI] |", "| --- | --- | --- | --- |",
           f"| Welch t | t = {tw.statistic:.2f}, df = {tw.df:.1f} | {fmt_p(tw.p)} | +{tw.effect:.3f} sccm {fmt_ci(tw.ci)} |",
           f"| pooled t | t = {tp.statistic:.2f}, df = {tp.df} | {fmt_p(tp.p)} | +{tp.effect:.3f} sccm |",
           f"| Mann-Whitney U (no normality needed) | U = {mw.statistic:.0f} | {fmt_p(mw.p)} | P(Thu-Fri > Mon-Tue) = {mw.effect:.2f} |",
           f"| F test, equal variances | F = {fv.statistic:.2f} | {fv.p:.3f} | variance ratio {fv.effect:.2f} |", "",
           "All five days at once:", "",
           "| Test | Statistic | p | Note |", "| --- | --- | --- | --- |",
           f"| one-way ANOVA | F({an.df[0]}, {an.df[1]}) = {an.statistic:.1f} | {fmt_p(an.p)} | "
           f"eta squared = {an.effect:.2f}: the day explains {100 * an.effect:.0f} % of the variation |",
           f"| Levene (median) | {lv.statistic:.2f} | {lv.p:.3f} | "
           + ("equal variances rejected: trust Kruskal-Wallis more than ANOVA |" if lv.reject()
              else "equal variances not rejected: ANOVA's assumption holds |"),
           f"| Kruskal-Wallis | H = {kw.statistic:.1f} | {fmt_p(kw.p)} | the rank test agrees |", "",
           "Tukey HSD, which pairs of days differ (family-wise 5 %):", "",
           "| | " + " | ".join(DAYS) + " |", "| --- |" + " --- |" * 5]
    for i, d1 in enumerate(DAYS):
        cells = []
        for j in range(5):
            if j <= i:
                cells.append("")
            else:
                diff = groups[j].mean() - groups[i].mean()
                cells.append(f"{diff:+.2f}{' *' if tukey.pvalue[i, j] < ALPHA else ''}")
        md.append(f"| {d1} | " + " | ".join(cells) + " |")
    steps = [f"{DAYS[i]} to {DAYS[i + 1]} {groups[i + 1].mean() - groups[i].mean():+.2f}"
             + (" (significant)" if tukey.pvalue[i, i + 1] < ALPHA else " (not significant)") for i in range(4)]
    md += ["", "(* = significant.) Day to day: " + "; ".join(steps) + ". The rise is spread over several days, a "
           "gradual wear rather than one jump; a single day-to-day step of about 0.2 sccm is too small to prove with "
           "30 parts a day, while the bigger gaps over two or more days are clear.", ""]
    out["tests"] = {"welch": vars(tw), "mann_whitney": vars(mw), "anova": vars(an), "levene": vars(lv), "kruskal": vars(kw)}

    # ================================================================ 5. change point + regression
    cand = np.round(np.arange(0.5, 4.5, 0.05), 2)
    (tau, a0, b0, sse), curve = st.hinge_fit(leak.t_day, leak.value, cand)
    rising = leak[leak.t_day >= tau]
    reg = st.linreg(rising.t_day, rising.value)
    slope = reg.t_slope()
    grid = np.linspace(tau, 8, 2000)
    yhat, lo95, hi95 = reg.predict(grid)
    cross = lambda arr: float(grid[np.argmax(arr >= 2.0)]) if (arr >= 2.0).any() else None  # noqa: E731
    t_mean, t_early, t_late = cross(yhat), cross(hi95), cross(lo95)

    def day_str(t):
        if t is None:
            return "-"
        d, frac = int(t), t - int(t)
        names = DAYS + ["next Mon", "next Tue", "next Wed", "next Thu"]
        hh = 6 + frac * 15
        return f"{names[d]} {int(hh):02d}:{int(round((hh % 1) * 60)) % 60:02d}"

    out["regression"] = {"tau": tau, "tau_str": day_str(tau), "slope_per_day": reg.b, "slope_ci": list(reg.ci_slope()),
                         "r2": reg.r2, "mean_reaches_2": day_str(t_mean), "ci": [day_str(t_early), day_str(t_late)]}
    md += ["## 5. When did the wear start, and where is it heading? (change point, regression)", "",
           "Segmented regression leak = a + b * max(0, t - tau), with the change point tau found by least squares over "
           "every 0.05 day (t in production days, Monday 06:00 = 0).", "",
           "| Result | Value |", "| --- | --- |",
           f"| estimated start of the wear | **{day_str(tau)}** (t = {tau:.2f}) |",
           f"| level before | {a0:.3f} sccm |",
           f"| slope after (least squares on the rising part) | {reg.b:.3f} sccm per day {fmt_ci(reg.ci_slope())}, "
           f"t = {slope.statistic:.1f}, {P(slope.p)} |",
           f"| R squared of the rising part | {reg.r2:.2f} |",
           f"| mean leak rate reaches the 2.0 sccm limit (half the parts fail) | **{day_str(t_mean)}**, "
           f"95 % band {day_str(t_early)} to {day_str(t_late)} |", "",
           "In the generator the wear starts at the beginning of Wednesday, in daily steps. The change point lands within "
           "one shift of it from the data alone; it comes out a little early because the model fits a straight line to "
           "what is really a staircase (Tukey in section 4 confirms Tuesday and Wednesday differ, Monday and Tuesday do not). "
           "The extrapolation assumes the wear stays linear, which is the weakest assumption in this report: it is a "
           "warning of the order of magnitude (days, not weeks), not a schedule.", ""]

    # ================================================================ 6. failure rates
    valid = runs[runs.result != "ABORT"]
    md += ["## 6. Which station fails most, and is it significant? (proportions)", "",
           "| Station | Runs | Failures | Fail rate | 95 % Wilson CI |", "| --- | --- | --- | --- | --- |"]
    out["fail_rates"] = {}
    for station, g in valid.groupby("station"):
        k, n = int((g.result == "FAIL").sum()), len(g)
        lo_, hi_ = st.ci_proportion(k, n)
        md.append(f"| {station} | {n} | {k} | {100 * k / n:.2f} % | {100 * lo_:.2f} to {100 * hi_:.2f} % |")
        out["fail_rates"][station] = k / n
    is_leak = valid.station == "LEAK-1"
    kl, nl = int((valid[is_leak].result == "FAIL").sum()), int(is_leak.sum())
    ko, no = int((valid[~is_leak].result == "FAIL").sum()), int((~is_leak).sum())
    tp2 = st.two_proportions(kl, nl, ko, no)
    _, fisher_p = sd.fisher_exact([[kl, nl - kl], [ko, no - ko]])
    tab = pd.crosstab(valid.station, valid.result)
    chi = st.chi2_independence(tab.to_numpy())
    small = int((chi.expected < 5).sum())
    md += ["", f"LEAK-1 against all other stations: two-proportion z = {tp2.statistic:.2f}, {P(tp2.p)}; "
           f"Fisher's exact test {P(fisher_p)}. "
           f"Chi-square of station x result: chi2 = {chi.statistic:.1f}, df = {chi.df}, {P(chi.p)}, but {small} of "
           f"{chi.expected.size} expected counts are below 5, so the chi-square approximation is not trustworthy here; "
           "Fisher's exact test is the right choice for so few failures.", "",
           "The confidence intervals overlap heavily: with 1-2 % failures, a few hundred runs per station is not enough "
           "to rank stations reliably by fail rate alone. The measurement values (sections 3-5) say far more than "
           "the pass/fail counts.", ""]
    out["leak_vs_rest"] = {"z": tp2.statistic, "p": tp2.p, "fisher_p": fisher_p}

    # daily p-chart for LEAK-1, all valid runs
    lk = valid[is_leak].groupby("day", observed=True).result
    kd = lk.apply(lambda s: (s == "FAIL").sum()).to_numpy()
    nd = lk.size().to_numpy()
    pbar = ko / no     # Monday-Tuesday had no LEAK-1 failures at all: p-bar 0 would give a useless chart
    pp, _, lclp, uclp = charts.p_chart(kd, nd, p_bar=pbar)
    md += ["Daily p-chart of LEAK-1. Monday and Tuesday had no failures, so a p-bar from phase I would be 0 and every "
           "single failure would be 'out of control'; with rare failures an attribute chart needs a long history. "
           f"Here p-bar is the fail rate of the other stations over the week, {100 * pbar:.2f} %: "
           + ", ".join(f"{d} {100 * v:.1f} % (UCL {100 * u:.1f} %){' **out**' if v > u else ''}"
                       for d, v, u in zip(DAYS, pp, uclp, strict=True)) + ". "
           "The attribute chart reacts only when parts already fail in numbers; the variables chart in "
           "section 3 warned on Wednesday morning.", ""]

    # first-pass yield of clutch units, Friday vs Monday-Thursday
    cl = runs[runs["product"] == "CRU-200"]
    fp = cl.groupby("serial_no").apply(lambda g: bool(((g.attempt == 1) & (g.result == "PASS")).sum() == g.station.nunique()),
                                       include_groups=False)
    day_of = cl.groupby("serial_no").day.first()
    fri = fp[day_of == "Fri"]
    rest = fp[day_of != "Fri"]
    t_fpy = st.two_proportions(int(fri.sum()), len(fri), int(rest.sum()), len(rest))
    _, fp_fisher = sd.fisher_exact([[int(fri.sum()), len(fri) - int(fri.sum())], [int(rest.sum()), len(rest) - int(rest.sum())]])
    md += [f"Clutch units first-pass yield: Friday {100 * fri.mean():.1f} % ({int(fri.sum())}/{len(fri)}) against "
           f"Monday-Thursday {100 * rest.mean():.1f} % ({int(rest.sum())}/{len(rest)}); difference "
           f"{100 * t_fpy.effect:+.1f} points, 95 % CI {100 * t_fpy.ci[0]:+.1f} to {100 * t_fpy.ci[1]:+.1f}; z test {P(t_fpy.p)}, "
           f"Fisher {P(fp_fisher)}.", ""]
    out["fpy"] = {"friday": float(fri.mean()), "rest": float(rest.mean()), "p": t_fpy.p, "fisher_p": fp_fisher}

    # ================================================================ 7. shift
    fa = valid[valid.attempt == 1]
    tab_s = pd.crosstab(fa["shift"], fa.result)
    chi_s = st.chi2_independence(tab_s.to_numpy())
    rates = (tab_s["FAIL"] / tab_s.sum(axis=1)).to_dict()
    md += ["## 7. Does the shift matter? (chi-square test of independence)", "",
           f"First attempts, shift x result: shift A {100 * rates['A']:.2f} % failures, shift B {100 * rates['B']:.2f} %; "
           f"chi2 = {chi_s.statistic:.2f}, df = 1, {P(chi_s.p)}, Cramer's V = {chi_s.effect:.3f}. "
           f"{'H0 (independence) is not rejected' if not chi_s.reject() else 'H0 is rejected'}: no evidence that the shift "
           "matters. That is not proof that it doesn't; with so few failures the test could only detect a large difference.", ""]
    out["shift"] = {"chi2": chi_s.statistic, "p": chi_s.p, "rates": rates}

    # ================================================================ 8. retests
    rt = m[(m.spec_id == 5) & (m.attempt == 2)]
    late_first = leak[leak.day.isin(["Thu", "Fri"])].value
    w_rt = st.welch_t(rt.value, late_first)
    md += ["## 8. Are the retests honest? (Welch test, regression to the mean)", "",
           f"{len(rt)} LEAK-1 parts were retested after failing. Their retest values average {rt.value.mean():.3f} sccm, "
           f"against {late_first.mean():.3f} sccm for first attempts on Thursday-Friday: difference {w_rt.effect:+.3f} sccm, "
           f"95 % CI {fmt_ci(w_rt.ci)}, Welch {P(w_rt.p)}. The retests read like an unworn seal "
           f"(Monday-Tuesday mean {a.mean():.3f}).", "",
           "Some drop is expected even if nothing changed (regression to the mean: parts selected because they read "
           "high will read lower next time), but not this much. Re-seating the part temporarily hides the wear, and "
           "every rescued part makes the station look healthier than it is. A retest rule should require the second "
           "reading to be close to the first, not just inside the limit.", ""]
    out["retest"] = {"n": len(rt), "mean_retest": float(rt.value.mean()), "mean_first_thu_fri": float(late_first.mean()), "p": w_rt.p}

    # ================================================================ 9. a stable process: Xbar-R
    tq = first[first.spec_id == 9].value.to_numpy()
    nsub = tq.size // 5
    subs = tq[:nsub * 5].reshape(nsub, 5)
    sub_day = first[first.spec_id == 9].day.to_numpy()[:nsub * 5:5]
    ph1_sub = np.isin(sub_day, PHASE1)
    xr = charts.xbar_r_chart(subs, ph1_sub)
    xr_signals = sum(len(v) for v in xr.signals.values())
    md += ["## 9. A process that is in control (Xbar-R chart)", "",
           f"TORQ-2 torque, {nsub} subgroups of 5 consecutive actuators, limits from Monday-Tuesday "
           f"({int(ph1_sub.sum())} subgroups): centre {xr.limits.centre:.3f} Nm, limits {xr.limits.lcl:.3f} to {xr.limits.ucl:.3f} Nm, "
           f"R-bar {xr.secondary[1].centre:.3f} Nm. Western Electric signals: {xr_signals}. "
           "The torque process did not change during the week, and the chart correctly stays quiet: a control chart "
           "is only useful if it also says nothing when nothing happened.", ""]
    out["xbar_r"] = {"signals": xr_signals, "centre": xr.limits.centre, "lcl": xr.limits.lcl, "ucl": xr.limits.ucl}

    # ================================================================ 10. correlation
    eol2 = first[first.station == "EOL-2"].pivot_table(index="run_id", columns="quantity", values="value").dropna()
    pr = st.pearson(eol2["current"], eol2["stroke"])
    md += ["## 10. Are two measurements related? (correlation)", "",
           f"EOL-2 measures the actuator current and stroke in the same run (n = {len(eol2)}): r = {pr.effect:.3f}, "
           f"95 % CI {fmt_ci(pr.ci)}, {P(pr.p)}. No evidence of a relation, so a high current does not predict "
           "a short stroke here and both limits have to be checked separately.", ""]
    out["correlation"] = {"r": pr.effect, "ci": list(pr.ci), "p": pr.p}

    # ================================================================ write
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results/report.md").write_text("\n".join(md))
    (ROOT / "results/summary.json").write_text(json.dumps(out, indent=2, default=lambda o: o.tolist() if hasattr(o, "tolist") else str(o)))
    figures(leak, chart, ph1, z, ewl, ewu, when, tau, a0, reg, curve, cand, first, pp, uclp, xr, ph1_sub)
    print("\n".join(md))


